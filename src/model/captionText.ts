/**
 * 図・表のタイトルの頭に打った番号（「図1 デザイン画」「表2．使用材料」）を外す。番号は紙面で自動で付くため、そのままだと
 * 「図1.図1 デザイン画」と二重になる（PC の試し 2026-10-24。依頼者の選択：書き終えたときに自動で外して、知らせる）。
 * 「図1に示す…」のように番号のすぐ後ろに助詞などが続くもの、図のタイトルの「表1」（反対の字）は外さない。外さなければ、そのまま返す
 */
export function captionWithoutNumber(kind: '図' | '表', text: string): string {
  const m = /^[\s\u3000]*([図表])[\s\u3000]*[0-9０-９]+(?![0-9０-９])([\s\u3000]*[.．:：、,，\-－‐・][\s\u3000]*|[\s\u3000]+)?(.*)$/s.exec(text)
  if (!m || m[1] !== kind) return text
  const rest = m[3]
  if (!m[2] && /^[はにのをでがともへやよ枚つ列行点個種着か]/.test(rest)) return text
  return rest
}
